// Writes the About page's licence list from package.json + node_modules.
// Run after changing dependencies: `node scripts/gen-licences.mjs`.
// A test (about/licences.test.ts) fails if the list drifts from package.json.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));

const repoUrl = (meta) => {
  const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url;
  const raw = meta.homepage ?? repo ?? `https://www.npmjs.com/package/${meta.name}`;
  return raw
    .replace(/^git\+/u, '')
    .replace(/^git:\/\//u, 'https://')
    .replace(/\.git$/u, '')
    .replace(/^github:/u, 'https://github.com/');
};

const entries = Object.keys(pkg.dependencies)
  .sort()
  .map((name) => {
    const meta = JSON.parse(
      readFileSync(path.join(root, 'node_modules', name, 'package.json'), 'utf8'),
    );
    const license =
      typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? 'UNKNOWN');
    return { name, version: meta.version, license, url: repoUrl(meta) };
  });

const out = `// Generated by scripts/gen-licences.mjs from package.json. Do not edit by hand.
export const APP_VERSION = ${JSON.stringify(pkg.version)};

export interface LicenceEntry {
  name: string;
  version: string;
  license: string;
  url: string;
}

/** Runtime dependencies shipped in the app bundle. */
export const LICENCES: readonly LicenceEntry[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(path.join(root, 'src/ui/features/settings/about/licences.generated.ts'), out);
console.log(`wrote ${entries.length} entries`);
